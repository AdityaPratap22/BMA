export function getGraphicDesignItemBySlug(slug: string): GraphicDesignItem | undefined {
  const clean = slug.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return GRAPHIC_DESIGN_ITEMS.find(
    (i) => i.slug === clean || i.slug === slug || (i.aliases && i.aliases.includes(clean))
  );
}

export function getGraphicDesignCategoryBySlug(slug: string): GraphicDesignCategory | undefined {
  const clean = slug.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return GRAPHIC_DESIGN_CATEGORIES_DATA.find(
    (c) =>
      c.slug === clean ||
      c.slug === slug ||
      (clean === 'large-format-branding' && c.slug === 'large-format-corporate-branding')
  );
}

export function getAllGraphicDesignSlugs(): string[] {
  const itemSlugs = GRAPHIC_DESIGN_ITEMS.map((i) => i.slug);
  const catSlugs = GRAPHIC_DESIGN_CATEGORIES_DATA.map((c) => c.slug);
  return Array.from(new Set([...itemSlugs, ...catSlugs]));
}

export function getRelatedGraphicDesignItems(slug: string, limit: number = 4): GraphicDesignItem[] {
  const current = getGraphicDesignItemBySlug(slug);
  if (!current) return GRAPHIC_DESIGN_ITEMS.slice(0, limit);
  return GRAPHIC_DESIGN_ITEMS.filter(
    (i) => i.slug !== current.slug && i.categorySlug === current.categorySlug
  ).slice(0, limit);
}
